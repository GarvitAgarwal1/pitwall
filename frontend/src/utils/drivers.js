/**
 * Returns a normalized driver profile from driver code or identifier
 */
export function getDriverProfile(identifier) {
  if (!identifier) return null;
  const key = String(identifier).trim().toUpperCase();

  if (DRIVER_PROFILES[key]) return DRIVER_PROFILES[key];

  // Try matching by surname or partial slug
  const lower = String(identifier).toLowerCase();
  for (const prof of Object.values(DRIVER_PROFILES)) {
    if (
      prof.name.toLowerCase().includes(lower) ||
      lower.includes(prof.code.toLowerCase()) ||
      lower.includes(prof.team.toLowerCase())
    ) {
      return prof;
    }
  }

  // Generic fallback profile
  return {
    code: key.slice(0, 3),
    number: 99,
    name: identifier,
    team: 'Formula 1',
    teamId: 'default',
    nationality: 'International',
    flag: '🏁',
    image: 'https://media.formula1.com/d_driver_fallback_image.png/content/dam/fom-website/drivers/placeholder.png',
    championships: 0,
    color: '#64748B',
  };
}

